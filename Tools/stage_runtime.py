"""Stages Telescreen's runtime components into Resources/Runtime/<component>/ and writes the compiled-in manifest.

  python Tools/stage_runtime.py

Components (see D:/SFMod/Tools/RuntimeComponents.md):
  host     TelescreenHost.exe (built by Helper/build.bat) and the FFmpeg LGPL DLLs it links
  fetcher  yt-dlp.exe and QuickJS (qjs.exe), which yt-dlp uses for YouTube's challenges

Third-party files come from D:/SFMod/Tools (pinned downloads) and are checked against the pins below before copying.
The manifest (Source/Telescreen/Private/Runtime/TSRuntimeManifest.inl) lists every staged file with its size and
SHA-256; rebuild the mod after staging so the manifest matches.
"""
import hashlib
import os
import shutil
import sys

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = r'D:/SFMod/Tools'
FFMPEG = os.path.join(TOOLS, 'ffmpeg', 'ffmpeg-n8.1.3-win64-lgpl-shared-8.1')
RUNTIME = os.path.join(MOD, 'Resources', 'Runtime')
MANIFEST = os.path.join(MOD, 'Source', 'Telescreen', 'Private', 'Runtime', 'TSRuntimeManifest.inl')

PINS = {
    os.path.join(TOOLS, 'yt-dlp.exe'): '66674953fe251b89f4d08c5f0e35e0728679bd67ab3d7d05c0562af101dd3e7a',
    os.path.join(TOOLS, 'qjs', 'qjs.exe'): '2aeabf0092c3262d6b2609824418f7dd7ed1f1df939f73b2b15645230cac0d77',
}

COMPONENTS = {
    'host': {
        'version': '0.1.0+ffmpeg-n8.1.3',
        'files': [
            (os.path.join(MOD, 'Helper', 'out', 'TelescreenHost.exe'), 'TelescreenHost.exe'),
            *[(os.path.join(FFMPEG, 'bin', f'{dll}.dll'), f'{dll}.dll')
              for dll in ('avformat-62', 'avcodec-62', 'avutil-60', 'swscale-9', 'swresample-6')],
            (os.path.join(FFMPEG, 'LICENSE.txt'), 'LICENSE-FFmpeg.txt'),
        ],
    },
    'fetcher': {
        'version': 'yt-dlp-2026.08.19+quickjs-ng-0.17.0',
        'files': [
            (os.path.join(TOOLS, 'yt-dlp.exe'), 'yt-dlp.exe'),
            (os.path.join(TOOLS, 'qjs', 'qjs.exe'), 'qjs.exe'),
            (os.path.join(TOOLS, 'qjs', 'LICENSE'), 'LICENSE-QuickJS.txt'),
        ],
        'texts': {
            'LICENSE-yt-dlp.txt': 'yt-dlp is released into the public domain under the Unlicense: https://unlicense.org/\n'
                                  'Source: https://github.com/yt-dlp/yt-dlp\n',
        },
    },
}


def sha256(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            digest.update(block)
    return digest.hexdigest()


def main():
    lines = ['// Generated by Tools/stage_runtime.py; do not edit.',
             '// TS_RUNTIME_COMPONENT(Id, Version)  TS_RUNTIME_FILE(Id, RelativePath, Size, Sha256)']
    for component, spec in COMPONENTS.items():
        dest = os.path.join(RUNTIME, component)
        shutil.rmtree(dest, ignore_errors=True)
        os.makedirs(dest)
        for source, name in spec['files']:
            if not os.path.isfile(source):
                sys.exit(f'missing {source}')
            if source in PINS and sha256(source) != PINS[source]:
                sys.exit(f'{source} does not match its pinned SHA-256')
            shutil.copy2(source, os.path.join(dest, name))
        for name, text in spec.get('texts', {}).items():
            with open(os.path.join(dest, name), 'w', newline='\n') as f:
                f.write(text)
        lines.append(f'TS_RUNTIME_COMPONENT(TEXT("{component}"), TEXT("{spec["version"]}"))')
        for name in sorted(os.listdir(dest)):
            path = os.path.join(dest, name)
            lines.append(f'TS_RUNTIME_FILE(TEXT("{component}"), TEXT("{name}"), {os.path.getsize(path)}, TEXT("{sha256(path)}"))')
        print(f'{component}: {len(os.listdir(dest))} files')
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    with open(MANIFEST, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'manifest: {MANIFEST}')


if __name__ == '__main__':
    main()
